/// Build a simple HTTP-like state machine for testing.
#[must_use]
pub fn http_like_state_machine() -> NetworkStateMachine {
    let initial = State::Builtin(ProtocolState::Initial);
    let connected = State::Builtin(ProtocolState::Connected);
    let data = State::Builtin(ProtocolState::DataTransfer);
    let closing = State::Builtin(ProtocolState::Closing);
    let closed = State::Builtin(ProtocolState::Closed);

    let mut fsm = NetworkStateMachine::new(initial.clone());

    // SYN
    let mut syn = MessageTemplate::new("TCP_SYN");
    syn.add_field(FieldType::FixedBytes(b"SYN".to_vec()));
    fsm.add_transition(Transition::new(initial, connected.clone(), "connect", syn));

    // HTTP GET
    let mut get = MessageTemplate::new("HTTP_GET");
    get.add_field(FieldType::AsciiString(
        "GET /fuzz HTTP/1.1\r\n\r\n".to_string(),
    ));
    fsm.add_transition(Transition::new(connected, data.clone(), "request", get));

    // Data post
    let mut post = MessageTemplate::new("HTTP_POST");
    post.add_field(FieldType::RandomBytes {
        min_len: 4,
        max_len: 256,
    });
    fsm.add_transition(Transition::new(
        data.clone(),
        data.clone(),
        "transfer",
        post,
    ));

    // Close
    let mut fin = MessageTemplate::new("TCP_FIN");
    fin.add_field(FieldType::FixedBytes(b"FIN".to_vec()));
    fsm.add_transition(Transition::new(data, closing.clone(), "close", fin));

    let mut ack = MessageTemplate::new("TCP_ACK");
    ack.add_field(FieldType::FixedBytes(b"ACK".to_vec()));
    fsm.add_transition(Transition::new(closing, closed, "ack_close", ack));

    fsm
}

