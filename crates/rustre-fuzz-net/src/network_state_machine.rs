//! Network protocol state machine for fuzzing (`rustre-fuzz-net`).
//!
//! Models a network protocol as a finite state machine.  Each state has
//! transitions (guarded, with actions) and message templates.  The
//! [`StateMachineFuzzer`] drives the machine while mutating message fields.

pub use std::collections::HashMap;
use std::fmt;

use serde::{Deserialize, Serialize};

// ---------------------------------------------------------------------------
// State
// ---------------------------------------------------------------------------

/// States of a generic TCP/application-layer protocol.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum ProtocolState {
    Initial,
    Connected,
    Authenticated,
    DataTransfer,
    Closing,
    Error,
    Closed,
}

impl ProtocolState {
    /// Returns `true` if this is a terminal state.
    #[must_use]
    pub const fn is_terminal(self) -> bool {
        matches!(self, Self::Closed | Self::Error)
    }
}

impl fmt::Display for ProtocolState {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let s = match self {
            Self::Initial => "Initial",
            Self::Connected => "Connected",
            Self::Authenticated => "Authenticated",
            Self::DataTransfer => "DataTransfer",
            Self::Closing => "Closing",
            Self::Error => "Error",
            Self::Closed => "Closed",
        };
        write!(f, "{s}")
    }
}

// ---------------------------------------------------------------------------
// User-defined State (for custom protocols)
// ---------------------------------------------------------------------------

/// A user-defined state for protocols with more than the built-in states.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct CustomState {
    pub id: u32,
    pub name: String,
    pub is_terminal: bool,
}

impl CustomState {
    #[must_use]
    pub fn new(id: u32, name: impl Into<String>) -> Self {
        Self {
            id,
            name: name.into(),
            is_terminal: false,
        }
    }

    #[must_use]
    pub const fn terminal(mut self) -> Self {
        self.is_terminal = true;
        self
    }
}

/// A state node in the FSM (either built-in or custom).
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum State {
    Builtin(ProtocolState),
    Custom(CustomState),
}

impl State {
    #[must_use]
    pub const fn is_terminal(&self) -> bool {
        match self {
            Self::Builtin(s) => s.is_terminal(),
            Self::Custom(s) => s.is_terminal,
        }
    }

    #[must_use]
    pub fn name(&self) -> String {
        match self {
            Self::Builtin(s) => s.to_string(),
            Self::Custom(s) => s.name.clone(),
        }
    }
}

impl fmt::Display for State {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.name())
    }
}

// ---------------------------------------------------------------------------
// MessageTemplate
// ---------------------------------------------------------------------------

/// Field type in a message template.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum FieldType {
    FixedBytes(Vec<u8>),
    RandomBytes { min_len: usize, max_len: usize },
    U8(u8),
    U16Le(u16),
    U32Le(u32),
    U64Le(u64),
    AsciiString(String),
    LengthPrefixed { inner: Box<Self> },
}

impl FieldType {
    /// Generate bytes from this field, using `rng` for random fields.
    #[must_use]
    pub fn generate(&self, rng: &mut SimpleRng) -> Vec<u8> {
        match self {
            Self::FixedBytes(b) => b.clone(),
            Self::RandomBytes { min_len, max_len } => {
                let len = min_len + rng.next_range(max_len - min_len + 1);
                (0..len).map(|_| rng.next_byte()).collect()
            }
            Self::U8(v) => vec![*v],
            Self::U16Le(v) => v.to_le_bytes().to_vec(),
            Self::U32Le(v) => v.to_le_bytes().to_vec(),
            Self::U64Le(v) => v.to_le_bytes().to_vec(),
            Self::AsciiString(s) => s.as_bytes().to_vec(),
            Self::LengthPrefixed { inner } => {
                let data = inner.generate(rng);
                let mut out = vec![data.len() as u8];
                out.extend(data);
                out
            }
        }
    }

    /// Mutate the generated bytes.
    pub fn mutate(&mut self, rng: &mut SimpleRng) {
        match self {
            Self::FixedBytes(b) if !b.is_empty() => {
                let idx = rng.next_range(b.len());
                b[idx] ^= rng.next_byte();
            }
            Self::U8(v) => *v = rng.next_byte(),
            Self::U16Le(v) => *v = rng.next_u16(),
            Self::U32Le(v) => *v = rng.next_u32(),
            Self::AsciiString(s) if !s.is_empty() => {
                let idx = rng.next_range(s.len());
                let mut chars: Vec<char> = s.chars().collect();
                chars[idx] = (rng.next_range(26) as u8 + b'a') as char;
                *s = chars.into_iter().collect();
            }
            _ => {}
        }
    }
}

/// A message template consists of ordered fields.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MessageTemplate {
    pub name: String,
    pub fields: Vec<FieldType>,
    /// Whether this message is fuzz-able (mutated during fuzzing).
    pub fuzzable: bool,
}

impl MessageTemplate {
    #[must_use]
    pub fn new(name: impl Into<String>) -> Self {
        Self {
            name: name.into(),
            fields: Vec::new(),
            fuzzable: true,
        }
    }

    pub fn add_field(&mut self, field: FieldType) {
        self.fields.push(field);
    }

    /// Generate message bytes.
    #[must_use]
    pub fn generate(&self, rng: &mut SimpleRng) -> Vec<u8> {
        self.fields.iter().flat_map(|f| f.generate(rng)).collect()
    }

    /// Generate a mutated version of the message.
    #[must_use]
    pub fn generate_mutated(&self, rng: &mut SimpleRng) -> Vec<u8> {
        if !self.fuzzable {
            return self.generate(rng);
        }
        let mut template = self.clone();
        // Mutate a random field.
        if !template.fields.is_empty() {
            let idx = rng.next_range(template.fields.len());
            template.fields[idx].mutate(rng);
        }
        template.generate(rng)
    }
}

// ---------------------------------------------------------------------------
// Transition
// ---------------------------------------------------------------------------

/// A guard function: `fn(state, message) -> bool`.
pub type GuardFn = Box<dyn Fn(&State, &[u8]) -> bool + Send + Sync>;

/// An action function: `fn(message) -> Option<response>`.
pub type ActionFn = Box<dyn Fn(&[u8]) -> Option<Vec<u8>> + Send + Sync>;

/// A state machine transition.
pub struct Transition {
    /// Source state.
    pub from: State,
    /// Destination state.
    pub to: State,
    /// Human-readable label.
    pub label: String,
    /// Message template to send when taking this transition.
    pub message: MessageTemplate,
    /// Guard: if `Some`, must return `true` for the transition to be taken.
    pub guard: Option<GuardFn>,
    /// Action executed when the transition is taken.
    pub action: Option<ActionFn>,
}

impl Transition {
    /// Create a simple transition with no guard or action.
    #[must_use]
    pub fn new(from: State, to: State, label: impl Into<String>, message: MessageTemplate) -> Self {
        Self {
            from,
            to,
            label: label.into(),
            message,
            guard: None,
            action: None,
        }
    }

    /// Check if the guard allows this transition (always true if no guard).
    #[must_use]
    pub fn check_guard(&self, current: &State, msg: &[u8]) -> bool {
        self.guard.as_ref().is_none_or(|g| g(current, msg))
    }

    /// Execute the action and return an optional response.
    #[must_use]
    pub fn execute_action(&self, msg: &[u8]) -> Option<Vec<u8>> {
        self.action.as_ref().and_then(|a| a(msg))
    }
}

impl fmt::Debug for Transition {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "Transition({} → {} [{}])",
            self.from, self.to, self.label
        )
    }
}

// ---------------------------------------------------------------------------
// NetworkStateMachine
// ---------------------------------------------------------------------------

/// A finite state machine representing a network protocol.
pub struct NetworkStateMachine {
    pub current_state: State,
    pub initial_state: State,
    pub transitions: Vec<Transition>,
    /// History of visited states.
    pub history: Vec<State>,
    /// Messages sent in this session.
    pub sent_messages: Vec<Vec<u8>>,
}

impl NetworkStateMachine {
    /// Create an FSM starting in `initial_state`.
    #[must_use]
    pub fn new(initial_state: State) -> Self {
        Self {
            current_state: initial_state.clone(),
            initial_state,
            transitions: Vec::new(),
            history: Vec::new(),
            sent_messages: Vec::new(),
        }
    }

    /// Add a transition.
    pub fn add_transition(&mut self, transition: Transition) {
        self.transitions.push(transition);
    }

    /// Find all transitions from the current state.
    #[must_use]
    pub fn available_transitions(&self) -> Vec<&Transition> {
        self.transitions
            .iter()
            .filter(|t| t.from == self.current_state)
            .collect()
    }

    /// Take a random transition from the current state using `rng`.
    ///
    /// Returns the message bytes sent, or `None` if no transition is available.
    pub fn step(&mut self, rng: &mut SimpleRng) -> Option<Vec<u8>> {
        let available: Vec<usize> = self
            .transitions
            .iter()
            .enumerate()
            .filter(|(_, t)| t.from == self.current_state)
            .map(|(i, _)| i)
            .collect();

        if available.is_empty() {
            return None;
        }
        let idx = available[rng.next_range(available.len())];

        let msg = self.transitions[idx].message.generate_mutated(rng);
        if self.transitions[idx].check_guard(&self.current_state, &msg) {
            self.history.push(self.current_state.clone());
            let next = self.transitions[idx].to.clone();
            self.sent_messages.push(msg.clone());
            self.current_state = next;
            Some(msg)
        } else {
            Some(msg) // guard failed, still return msg but don't advance
        }
    }

    /// Reset to the initial state.
    pub fn reset(&mut self) {
        self.current_state = self.initial_state.clone();
        self.history.clear();
        self.sent_messages.clear();
    }

    /// Whether we are in a terminal state.
    #[must_use]
    pub const fn is_terminal(&self) -> bool {
        self.current_state.is_terminal()
    }
}

