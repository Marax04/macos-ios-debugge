/// Explores the state machine graph by BFS/DFS to find all reachable states.
#[derive(Debug, Default)]
pub struct StateExplorer {
    pub visited_states: Vec<State>,
    pub edges: Vec<(State, State, String)>,
}

impl StateExplorer {
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// BFS exploration of the FSM graph.
    pub fn explore_bfs(&mut self, fsm: &NetworkStateMachine) {
        use std::collections::{HashSet, VecDeque};
        let mut visited: HashSet<String> = HashSet::new();
        let mut queue: VecDeque<State> = VecDeque::new();

        queue.push_back(fsm.initial_state.clone());
        visited.insert(fsm.initial_state.name());

        while let Some(state) = queue.pop_front() {
            self.visited_states.push(state.clone());
            for t in &fsm.transitions {
                if t.from == state && !visited.contains(&t.to.name()) {
                    visited.insert(t.to.name());
                    self.edges
                        .push((state.clone(), t.to.clone(), t.label.clone()));
                    queue.push_back(t.to.clone());
                }
            }
        }
    }

    /// Return all unique state names found.
    #[must_use]
    pub fn state_names(&self) -> Vec<String> {
        self.visited_states.iter().map(State::name).collect()
    }

    /// Number of distinct edges discovered.
    #[must_use]
    pub const fn edge_count(&self) -> usize {
        self.edges.len()
    }
}

// ---------------------------------------------------------------------------
// StateMachineFuzzer
// ---------------------------------------------------------------------------

/// Drives the FSM through random transitions, collecting generated messages
/// as fuzzer inputs.
pub struct StateMachineFuzzer {
    pub fsm: NetworkStateMachine,
    pub rng: SimpleRng,
    /// Maximum steps per session.
    pub max_steps: usize,
    /// Collected inputs (sessions × messages).
    pub corpus: Vec<Vec<Vec<u8>>>,
}

impl StateMachineFuzzer {
    #[must_use]
    pub const fn new(fsm: NetworkStateMachine, seed: u64) -> Self {
        Self {
            fsm,
            rng: SimpleRng::new(seed),
            max_steps: 64,
            corpus: Vec::new(),
        }
    }

    /// Run one fuzzing session: drive the FSM for up to `max_steps` steps.
    /// Returns the messages generated.
    #[must_use]
    pub fn run_session(&mut self) -> Vec<Vec<u8>> {
        self.fsm.reset();
        let mut session = Vec::new();
        for _ in 0..self.max_steps {
            if self.fsm.is_terminal() {
                break;
            }
            if let Some(msg) = self.fsm.step(&mut self.rng) {
                session.push(msg);
            } else {
                break;
            }
        }
        self.corpus.push(session.clone());
        session
    }

    /// Run `n` sessions and return the total number of messages generated.
    pub fn run_sessions(&mut self, n: usize) -> usize {
        (0..n).map(|_| self.run_session().len()).sum()
    }

    /// Return all unique messages across all sessions.
    #[must_use]
    pub fn unique_messages(&self) -> Vec<&Vec<u8>> {
        let mut seen = std::collections::HashSet::new();
        let mut out = Vec::new();
        for session in &self.corpus {
            for msg in session {
                if seen.insert(msg.as_slice()) {
                    out.push(msg);
                }
            }
        }
        out
    }
}

// ---------------------------------------------------------------------------
// SimpleRng
// ---------------------------------------------------------------------------

/// Fast xorshift64 PRNG.
#[derive(Debug, Clone)]
pub struct SimpleRng(u64);

impl SimpleRng {
    #[must_use]
    pub const fn new(seed: u64) -> Self {
        Self(if seed == 0 { 1 } else { seed })
    }

    pub const fn next_u64(&mut self) -> u64 {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 7;
        self.0 ^= self.0 << 17;
        self.0
    }

    pub const fn next_byte(&mut self) -> u8 {
        self.next_u64() as u8
    }

    pub const fn next_u16(&mut self) -> u16 {
        self.next_u64() as u16
    }

    pub const fn next_u32(&mut self) -> u32 {
        self.next_u64() as u32
    }

    pub const fn next_range(&mut self, n: usize) -> usize {
        if n == 0 {
            return 0;
        }
        (self.next_u64() as usize) % n
    }
}

