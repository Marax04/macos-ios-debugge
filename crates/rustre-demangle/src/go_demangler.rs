/// Return a human-readable description for well-known Go runtime symbols.
#[must_use]
pub fn describe_runtime_symbol(name: &str) -> Option<&'static str> {
    match name {
        "runtime.goexit" => Some("goroutine exit trampoline"),
        "runtime.morestack" => Some("stack growth trampoline"),
        "runtime.morestack_noctxt" => Some("stack growth (no context)"),
        "runtime.gcWriteBarrier" => Some("GC write barrier"),
        "runtime.duffzero" => Some("bulk zero (Duff's device)"),
        "runtime.duffcopy" => Some("bulk copy (Duff's device)"),
        "runtime.panicIndex" => Some("panic: index out of range"),
        "runtime.panicSlice" => Some("panic: slice out of bounds"),
        "runtime.panicNilPtr" => Some("panic: nil pointer dereference"),
        "runtime.throw" => Some("fatal runtime error"),
        "runtime.mallocgc" => Some("allocate heap object"),
        "runtime.newobject" => Some("allocate single object"),
        "runtime.makeslice" => Some("make a slice"),
        "runtime.makemap" => Some("make a map"),
        "runtime.chanrecv1" | "runtime.chanrecv2" => Some("channel receive"),
        "runtime.chansend1" => Some("channel send"),
        "runtime.gopanic" => Some("initiate a panic"),
        "runtime.gorecover" => Some("recover from a panic"),
        "runtime.convI2I" => Some("interface to interface conversion"),
        "runtime.convT64" | "runtime.convTstring" => Some("concrete to interface conversion"),
        "runtime.assertI2I" => Some("interface type assertion"),
        "runtime.assertE2T" => Some("empty interface to concrete type assertion"),
        _ => None,
    }
}

