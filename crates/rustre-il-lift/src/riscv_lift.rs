//! RISC-V 64-bit complete lifter (RV64I + RV64M).
//!
//! # Relationship with [`crate::riscv_lifter`]
//!
//! This module ([`RiscV64Lifter`]) and [`crate::riscv_lifter::RiscvLifter`]
//! are **distinct capability layers**, not duplicates:
//!
//! | Feature                              | `riscv_lift` (`RiscV64Lifter`) | `riscv_lifter` (`RiscvLifter`) |
//! |--------------------------------------|--------------------------------|--------------------------------|
//! | RV32I / RV64I base ISA               | RV64 only                      | both (configurable `bits`)     |
//! | RV64M multiply / divide              | yes (`rv64m` flag)             | yes                            |
//! | RV64A atomics (LR/SC/AMO stubs)      | yes (`rv64a` flag)             | yes (via text fallback)        |
//! | CSR instructions (Zicsr)            | no                             | **yes**                        |
//! | Pseudo-branch coverage              | basic                          | **full** (BLEZ/BGEZ/BLTZ/BGTZ)|
//! | Text-operand fallback               | no                             | **yes** (robustness)           |
//! | Structured `Memory` operand support | partial                        | **full**                       |
//!
//! Use [`RiscV64Lifter`] for strictly typed RV64I+M pipelines where you control
//! the operand list.  Use [`crate::riscv_lifter::RiscvLifter`] for broader
//! disassembler input (objdump/LLVM text), CSR analysis, or RV32I targets.
//!
//! # Instruction coverage
//!
//! Covers the full base integer instruction set:
//!   RV64I: ADD/SUB/AND/OR/XOR/SLL/SRL/SRA/SLT/SLTU
//!          ADDI/ANDI/ORI/XORI/SLLI/SRLI/SRAI/SLTI/SLTIU
//!          LUI/AUIPC
//!          LB/LH/LW/LD/LBU/LHU/LWU / SB/SH/SW/SD
//!          BEQ/BNE/BLT/BGE/BLTU/BGEU
//!          JAL/JALR  ECALL/EBREAK
//!          ADDW/SUBW/SLLW/SRLW/SRAW + W-suffix immediates
//!   RV64M: MUL/MULH/MULHSU/MULHU/DIV/DIVU/REM/REMU
//!          MULW/DIVW/DIVUW/REMW/REMUW

