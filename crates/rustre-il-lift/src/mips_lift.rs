    use super::*;
    use rustre_core::address::Address;
    use rustre_core::arch::RegisterInfo;

    fn make_instr(mnemonic: &str, operands: &[Operand]) -> Instruction {
        let mut i = Instruction::new(Address::new(0x0040_0000), 4, mnemonic, vec![]);
        i.operand_list = operands.to_vec();
        i
    }

    fn reg_op(name: &str) -> Operand {
        Operand::Register(RegisterInfo::new(
            name,
            0,
            4,
            rustre_core::arch::RegisterKind::General,
        ))
    }
    fn imm_op(v: i64) -> Operand {
        Operand::Immediate(v)
    }
    fn lbl_op(v: u64) -> Operand {
        Operand::Label(v)
    }

    fn lft() -> Mips32Lifter {
        Mips32Lifter::new()
    }

    // Register normalisation
    #[test]
    fn norm_reg_dollar_zero() {
        assert_eq!(Mips32Lifter::norm_reg("$0"), "zero");
    }
    #[test]
    fn norm_reg_ra_number() {
        assert_eq!(Mips32Lifter::norm_reg("31"), "ra");
    }
    #[test]
    fn norm_reg_t9() {
        assert_eq!(Mips32Lifter::norm_reg("$t9"), "t9");
    }

    // ADD
    #[test]
    fn add_produces_add() {
        let i = make_instr("add", &[reg_op("t0"), reg_op("a0"), reg_op("a1")]);
        let effs = lft().lift_effects(&i);
        assert!(
            effs.iter().any(
                |e| matches!(e, Effect::RegWrite { reg, value: IrExpr::Add(..) } if reg == "t0")
            )
        );
    }

    // ADDU
