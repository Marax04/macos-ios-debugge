    fn reg(name: &str) -> IrExpr {
        IrExpr::Reg(Self::norm_reg(name))
    }

    fn op_reg(instr: &Instruction, i: usize) -> IrExpr {
        instr
            .operand_list
            .get(i)
            .and_then(|op| op.as_register())
            .map_or(IrExpr::Undef, |r| Self::reg(&r.name))
    }

    fn op_imm(instr: &Instruction, i: usize) -> IrExpr {
        instr
            .operand_list
            .get(i)
            .map_or(IrExpr::Undef, |op| match op {
                Operand::Immediate(v) => IrExpr::Const((*v).cast_unsigned()),
                Operand::UImmediate(v) => IrExpr::Const(*v),
                Operand::Register(r) => Self::reg(&r.name),
                Operand::Label(a) => IrExpr::Const(*a),
                _ => IrExpr::Undef,
            })
    }

    fn dest_name(instr: &Instruction) -> String {
        instr
            .operand_list
            .first()
            .and_then(|op| op.as_register()).map_or_else(|| "zero".to_string(), |r| Self::norm_reg(&r.name))
    }

    fn branch_target(instr: &Instruction) -> IrExpr {
        match instr.operand_list.last() {
            Some(Operand::Label(a)) => IrExpr::Const(*a),
            Some(Operand::Immediate(v)) => IrExpr::Const((*v).cast_unsigned()),
            Some(Operand::UImmediate(v)) => IrExpr::Const(*v),
            _ => IrExpr::Const(instr.address.0 + 4),
        }
    }

