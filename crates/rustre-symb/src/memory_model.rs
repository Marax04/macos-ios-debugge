    fn test_write_word_symbolic_decomposes() {
        let mut mem = SymbolicMemory::new();
        let val = SymExpr::var("x", SymType::BitVec(16));
        mem.write_word_symbolic(0x2000, &val, 2);
        assert!(mem.cells.contains_key(&0x2000));
        assert!(mem.cells.contains_key(&0x2001));
    }

    #[test]
    fn test_memory_cell_concrete() {
        let c = MemoryCell::Concrete(0xFF);
        assert!(c.is_concrete());
        assert_eq!(c.as_concrete_byte(), Some(0xFF));
        assert_eq!(c.to_sym_expr(0).as_const_u64(), Some(0xFF));
    }

    #[test]
    fn test_memory_cell_uninit_returns_var() {
        let c = MemoryCell::Uninit;
        assert!(!c.is_concrete());
        assert!(c.as_concrete_byte().is_none());
        assert!(matches!(c.to_sym_expr(0x42), SymExpr::Var { .. }));
    }
