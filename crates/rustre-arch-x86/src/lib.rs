/// Lift a single decoded `iced-x86` instruction via the main `X86Lifter`.
///
/// Returns a `Vec<LlilAnnotatedInstr>`. Delegates to the fully-implemented
/// [`lift::X86Lifter`]; the category sub-modules
/// (`lift_data_arith` / `lift_control_system` / `lift_fpu_simd`) are filled in
/// incrementally by the enterprise workflow.
#[must_use]
pub fn lift_to_llil(instr: &iced_x86::Instruction) -> Vec<rustre_il_llil::LlilAnnotatedInstr> {
    // Infer the bitness from the decoded instruction so 16/32-bit code is not
    // lifted with 64-bit pointer/stack widths. `CodeSize::Unknown` (e.g. an
    // `Instruction` built by hand rather than by a `Decoder`) falls back to 64.
    let bits = match instr.code_size() {
        iced_x86::CodeSize::Code16 => 16,
        iced_x86::CodeSize::Code32 => 32,
        _ => 64,
    };
    lift_to_llil_with_bits(instr, bits)
}

/// Like [`lift_to_llil`] but with an explicit target bitness (16, 32, or 64).
#[must_use]
pub fn lift_to_llil_with_bits(
    instr: &iced_x86::Instruction,
    bits: u32,
) -> Vec<rustre_il_llil::LlilAnnotatedInstr> {
    let mut lifter = X86Lifter::new(bits);
    lifter.lift(instr, Address::new(instr.ip()), instr.len())
}

/// Come [`lift_to_llil_with_bits`], ma i temporanei partono da `base` e la funzione
/// restituisce anche **quanti** ne ha allocati, cosi' che il chiamante possa filare la
/// numerazione all'istruzione successiva (#4400: senza questo, ogni istruzione riparte
/// da `Temporary(0)` e i nomi `tmp{n}` collidono).
///
/// `base` viene passato come **parametro**, non letto dall'ambiente: la logica resta
/// testabile senza variabili globali.
#[must_use]
pub fn lift_to_llil_from_base(
    instr: &iced_x86::Instruction,
    bits: u32,
    base: u32,
) -> (Vec<rustre_il_llil::LlilAnnotatedInstr>, u32) {
    let mut lifter = X86Lifter::with_temp_base(bits, base);
    let ops = lifter.lift(instr, Address::new(instr.ip()), instr.len());
    (ops, lifter.temp_count())
}

/// High-level architecture-aware lifter struct.
///
/// Wraps `lift_to_llil` and carries the target bitness so that callers can
/// query architecture metadata alongside lifting.
pub struct ArchX86Lifter {
    pub bits: u8,
}

impl ArchX86Lifter {
    /// Create a new lifter for the given bitness (16, 32, or 64).
    #[must_use]
    pub const fn new(bits: u8) -> Self {
        Self { bits }
    }

    /// Lift a single decoded instruction.
    #[must_use]
    pub fn lift_instruction(
        &self,
        instr: &iced_x86::Instruction,
    ) -> Vec<rustre_il_llil::LlilAnnotatedInstr> {
        lift_to_llil_with_bits(instr, u32::from(self.bits))
    }

    /// Returns the canonical architecture name for the configured bitness.
    #[must_use]
    pub const fn arch_name(&self) -> &str {
        match self.bits {
            64 => "x86_64",
            32 => "x86",
            16 => "x86_16",
            _ => "x86",
        }
    }
}

/// Decode and lift every instruction in `bytes` starting at virtual address
/// `ip` in `bits`-bit mode.
///
/// Returns a `Vec` of `(instruction_ip, Vec<LlilOp>)` pairs, one entry per
/// successfully decoded instruction.  Stops at the first invalid encoding.
#[must_use]
pub fn disassemble_and_lift(
    bytes: &[u8],
    ip: u64,
    bits: u8,
) -> Vec<(u64, Vec<rustre_il_llil::LlilAnnotatedInstr>)> {
    use iced_x86::{Decoder, DecoderOptions};
    let mut decoder = Decoder::with_ip(u32::from(bits), bytes, ip, DecoderOptions::NONE);
    let mut results = Vec::new();
    // Gate OPT-IN `RUSTRE_X86_TMPUNIQ` (#4400/#4410): quando acceso, la numerazione dei
    // temporanei prosegue da un'istruzione alla successiva invece di ripartire da 0,
    // eliminando la collisione dei nomi `tmp{n}`. Default SPENTO: accenderlo cambia
    // l'emissione di ENTRAMBI i path, quindi la decisione non e' automatica.
    let uniq = matches!(
        std::env::var("RUSTRE_X86_TMPUNIQ").as_deref(),
        Ok("1" | "true")
    );
    let mut base = 0u32;
    while decoder.can_decode() {
        let instr = decoder.decode();
        if instr.is_invalid() {
            break;
        }
        let ops = if uniq {
            let (ops, next) = lift_to_llil_from_base(&instr, u32::from(bits), base);
            base = next;
            ops
        } else {
            lift_to_llil_with_bits(&instr, u32::from(bits))
        };
        results.push((instr.ip(), ops));
    }
    results
}

