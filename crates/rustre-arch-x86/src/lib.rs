impl Architecture for X86Arch {
    fn name(&self) -> &str {
        match self.bits {
            16 => "x86_16",
            32 => "x86_32",
            64 => "x86_64",
            _ => "x86_unknown",
        }
    }

    fn pointer_size(&self) -> usize {
        match self.bits {
            16 => 2,
            32 => 4,
            64 => 8,
            _ => 8,
        }
    }

    fn endian(&self) -> Endian {
        Endian::Little
    }

    fn disassemble(&self, address: Address, bytes: &[u8]) -> Result<Instruction, CoreError> {
        let (iced, _len) = self.decode_one(address, bytes)?;
        Ok(self.convert(address, &iced, bytes))
    }

    fn get_branches(&self, instr: &Instruction) -> Vec<BranchInfo> {
        // Re-decode the instruction so we can call extract_branches on the
        // iced type.  The raw bytes are stored in the Instruction itself.
        if instr.bytes.is_empty() {
            return vec![];
        }
        match self.decode_one(instr.address, &instr.bytes) {
            Ok((iced, _)) => extract_branches(&iced),
            Err(_) => {
                // Graceful degradation: if re-decode somehow fails, fall back
                // to parsing the operands string that the old stub used.
                fallback_branches(instr)
            }
        }
    }

    fn registers(&self) -> Vec<RegisterInfo> {
        match self.bits {
            16 => registers_16bit(),
            32 => registers_32bit(),
            64 => registers_64bit(),
            _ => registers_64bit(),
        }
    }

    fn calling_conventions(&self) -> Vec<CallingConvention> {
        match self.bits {
            16 => vec![],
            32 => calling_conventions_32bit(),
            64 => calling_conventions_64bit(),
            _ => calling_conventions_64bit(),
        }
    }

    /// Lift a single instruction to LLIL operations via [`X86LiftAdapter`].
    ///
    /// This is the primary cross-crate integration point: it re-decodes the
    /// raw instruction bytes stored in `instr.bytes` with iced-x86, then
    /// dispatches to [`X86LiftAdapter::adapt_iced_to_llil`] which converts the
    /// iced representation to the [`LlilOp`] / [`IrExpr`] types from
    /// `rustre-core`.  The resulting ops are deposited into `ctx` so that
    /// callers can accumulate multiple instructions in one pass.
    ///
    /// # Errors
    ///
    /// Returns [`CoreError::PluginError`] if the bytes cannot be decoded by
    /// iced-x86.
    fn lift(&self, instr: &Instruction, ctx: &mut LiftContext) -> Result<Vec<LlilOp>, CoreError> {
        if instr.bytes.is_empty() {
            return Err(CoreError::PluginError {
                plugin: "x86".into(),
                message: "lift: instruction has no bytes".into(),
            });
        }

        // Re-decode with iced-x86 at the instruction's virtual address.
        let iced = X86LiftAdapter::decode_one_iced(self.bits, &instr.bytes, instr.address.0)
            .ok_or_else(|| CoreError::PluginError {
                plugin: "x86".into(),
                message: format!(
                    "lift: iced-x86 could not decode bytes at {:#x}",
                    instr.address.0
                ),
            })?;

        // Translate to LlilOp via the adapter.
        let ops = X86LiftAdapter::adapt_iced_to_llil(&iced, ctx);

        // Deposit each op into the context so label resolution works across
        // multiple calls.
        for op in &ops {
            ctx.emit(op.clone());
        }

        Ok(ops)
    }
}

