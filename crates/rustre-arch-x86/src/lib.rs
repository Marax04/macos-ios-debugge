/// Bridges the gap between the `rustre-arch-x86` [`Instruction`] type (which
/// stores raw bytes) and the flat [`LlilOp`] / [`LiftContext`] types from
/// `rustre-core`.
///
/// The adapter re-decodes the raw instruction bytes with `iced-x86`, then
/// translates the result to the flat `rustre-core` [`LlilOp`] representation
/// (using `GetReg(u32)` / `SetReg(u32)` / `Jump(u64)` / etc.) and deposits
/// the ops into the caller-supplied [`LiftContext`].
///
/// # Register ID scheme
///
/// | Hardware register group | IDs   |
/// |-------------------------|-------|
/// | RAX / EAX / AX / AL    | 0–3   |
/// | RBX / EBX / BX / BL    | 4–7   |
/// | RCX / ECX / CX / CL    | 8–11  |
/// | RDX / EDX / DX / DL    | 12–15 |
/// | RSI / ESI / SI / SIL   | 16–19 |
/// | RDI / EDI / DI / DIL   | 20–23 |
/// | RSP (all aliases)       | 24    |
/// | RBP (all aliases)       | 25    |
/// | R8–R15 (all aliases)    | 26–33 |
/// | RIP / EIP               | 34    |
/// | RFLAGS / EFLAGS / FLAGS | 35    | (reserved; iced-x86 exposes no flags Register variant) |
/// | XMM0–XMM15              | 36–51 |
/// | YMM0–YMM15              | 52–67 |
pub struct X86LiftAdapter {
    bits: u32,
}

impl X86LiftAdapter {
    /// Create an adapter for the given bitness (16, 32, or 64).
    #[must_use]
    pub const fn new(bits: u32) -> Self {
        Self { bits }
    }

    /// The bitness (16, 32, or 64) this adapter was constructed for.
    #[must_use]
    pub const fn bits(&self) -> u32 {
        self.bits
    }

    /// Decode one iced-x86 instruction from `bytes` at virtual address `ip`.
    ///
    /// Returns `None` if the bytes are empty or the decode produces an invalid
    /// instruction.
    #[must_use]
    pub fn decode_one_iced(bits: u32, bytes: &[u8], ip: u64) -> Option<IcedInstruction> {
        if bytes.is_empty() {
            return None;
        }
        let mut decoder = Decoder::with_ip(bits, bytes, ip, DecoderOptions::NONE);
        if !decoder.can_decode() {
            return None;
        }
        let iced = decoder.decode();
        if iced.is_invalid() { None } else { Some(iced) }
    }

    /// Map an iced-x86 register to a canonical `u32` register identifier.
    ///
    /// Returns [`u32::MAX`] for registers not covered by the scheme (segment
    /// registers, FPU stack, MMX, ZMM, debug and control registers).
    #[must_use]
    pub const fn reg_id(reg: iced_x86::Register) -> u32 {
        use iced_x86::Register as R;
        match reg {
            // ── RAX family ──────────────────────────────────────────────────
            R::RAX => 0,
            R::EAX => 1,
            R::AX => 2,
            R::AL => 3,
            // AH accesses bits 8-15 of AX — distinct from AL (bits 0-7); unique ID 68
            R::AH => 68,
            // ── RBX family ──────────────────────────────────────────────────
            R::RBX => 4,
            R::EBX => 5,
            R::BX => 6,
            R::BL => 7,
            // BH accesses bits 8-15 of BX — distinct from BL; unique ID 69
            R::BH => 69,
            // ── RCX family ──────────────────────────────────────────────────
            R::RCX => 8,
            R::ECX => 9,
            R::CX => 10,
            R::CL => 11,
            // CH accesses bits 8-15 of CX — distinct from CL; unique ID 70
            R::CH => 70,
            // ── RDX family ──────────────────────────────────────────────────
            R::RDX => 12,
            R::EDX => 13,
            R::DX => 14,
            R::DL => 15,
            // DH accesses bits 8-15 of DX — distinct from DL; unique ID 71
            R::DH => 71,
            // ── RSI family ──────────────────────────────────────────────────
            R::RSI => 16,
            R::ESI => 17,
            R::SI => 18,
            R::SIL => 19,
            // ── RDI family ──────────────────────────────────────────────────
            R::RDI => 20,
            R::EDI => 21,
            R::DI => 22,
            R::DIL => 23,
            // ── RSP — all size aliases share id 24 ──────────────────────────
            R::RSP | R::ESP | R::SP | R::SPL => 24,
            // ── RBP — all size aliases share id 25 ──────────────────────────
            R::RBP | R::EBP | R::BP | R::BPL => 25,
            // ── R8–R15 ──────────────────────────────────────────────────────
            R::R8 | R::R8D | R::R8W | R::R8L => 26,
            R::R9 | R::R9D | R::R9W | R::R9L => 27,
            R::R10 | R::R10D | R::R10W | R::R10L => 28,
            R::R11 | R::R11D | R::R11W | R::R11L => 29,
            R::R12 | R::R12D | R::R12W | R::R12L => 30,
            R::R13 | R::R13D | R::R13W | R::R13L => 31,
            R::R14 | R::R14D | R::R14W | R::R14L => 32,
            R::R15 | R::R15D | R::R15W | R::R15L => 33,
            // ── RIP / EIP ───────────────────────────────────────────────────
            R::RIP | R::EIP => 34,
            // ── RFLAGS / EFLAGS / FLAGS — ID 35 reserved ────────────────────
            // iced-x86 does not expose RFLAGS/EFLAGS/FLAGS as Register variants;
            // they are tracked implicitly via InstructionInfoFactory. ID 35 is
            // reserved in the scheme for future use when an explicit flags
            // register becomes available.
            // ── XMM0–XMM15 ──────────────────────────────────────────────────
            R::XMM0 => 36,
            R::XMM1 => 37,
            R::XMM2 => 38,
            R::XMM3 => 39,
            R::XMM4 => 40,
            R::XMM5 => 41,
            R::XMM6 => 42,
            R::XMM7 => 43,
            R::XMM8 => 44,
            R::XMM9 => 45,
            R::XMM10 => 46,
            R::XMM11 => 47,
            R::XMM12 => 48,
            R::XMM13 => 49,
            R::XMM14 => 50,
            R::XMM15 => 51,
            // ── YMM0–YMM15 ──────────────────────────────────────────────────
            R::YMM0 => 52,
            R::YMM1 => 53,
            R::YMM2 => 54,
            R::YMM3 => 55,
            R::YMM4 => 56,
            R::YMM5 => 57,
            R::YMM6 => 58,
            R::YMM7 => 59,
            R::YMM8 => 60,
            R::YMM9 => 61,
            R::YMM10 => 62,
            R::YMM11 => 63,
            R::YMM12 => 64,
            R::YMM13 => 65,
            R::YMM14 => 66,
            R::YMM15 => 67,
            // ── Everything else ─────────────────────────────────────────────
            _ => u32::MAX,
        }
    }

    /// Adapt a decoded `iced-x86` instruction to a `Vec<LlilOp>` using the
    /// flat `rustre-core` [`LlilOp`] representation.
    ///
    /// This is the central bridging function between the two crates.  The flat
    /// representation uses `GetReg(id)` / `SetReg(id)` pairs and constant
    /// instruction variants rather than expression trees, keeping the output
    /// compatible with `rustre-core`'s consumer interfaces.
    #[must_use]
    pub fn adapt_iced_to_llil(iced_instr: &IcedInstruction, _ctx: &mut LiftContext) -> Vec<LlilOp> {
        use iced_x86::Mnemonic as M;

        /// Emit `GetReg(id)` for the register at operand `n`, or a `Const(0)` for
        /// an immediate zero / unresolvable operand.
        fn src_reg(instr: &IcedInstruction, n: u32) -> LlilOp {
            match instr.op_kind(n) {
                OpKind::Register => {
                    LlilOp::GetReg(X86LiftAdapter::reg_id(instr.op_register(n)))
                }
                // A memory source is an honest memory read in the flat IR,
                // not a garbage constant (`immediate()` on a memory operand
                // returns 0/meaningless data).
                OpKind::Memory => LlilOp::Load,
                _ => LlilOp::Const(i128::from(instr.immediate(n))),
            }
        }

        /// Register id for operand `n`.
        fn reg_id_n(instr: &IcedInstruction, n: u32) -> u32 {
            if instr.op_kind(n) == OpKind::Register {
                X86LiftAdapter::reg_id(instr.op_register(n))
            } else {
                u32::MAX
            }
        }

        match iced_instr.mnemonic() {
            // ── data movement ──────────────────────────────────────────────
            M::Mov | M::Movsx | M::Movsxd | M::Movzx => {
                // dst = src : emit GetReg(src) followed by SetReg(dst)
                let src = src_reg(iced_instr, 1);
                let dst_id = reg_id_n(iced_instr, 0);
                if dst_id == u32::MAX {
                    // Memory destination: model as a Store
                    vec![src, LlilOp::Store]
                } else {
                    vec![src, LlilOp::SetReg(dst_id)]
                }
            }
            M::Lea => {
                // LEA dst, [mem]: for the flat IR we emit a Const(0) and SetReg.
                // A richer analysis pass resolves the effective address separately.
                let dst_id = reg_id_n(iced_instr, 0);
                vec![LlilOp::Const(0), LlilOp::SetReg(dst_id)]
            }
            M::Xchg => {
                let id0 = reg_id_n(iced_instr, 0);
                let id1 = reg_id_n(iced_instr, 1);
                // Correct swap using the flat stack IR:
                //   Push id1's original value first, then id0's original.
                //   SetReg(id1) pops id0's value → id1 now holds id0's original.
                //   SetReg(id0) pops id1's value → id0 now holds id1's original.
                // Both originals are read before any register is written,
                // avoiding the bug where GetReg(id1) after SetReg(id1) would
                // return the already-overwritten value.
                vec![
                    LlilOp::GetReg(id1),
                    LlilOp::GetReg(id0),
                    LlilOp::SetReg(id1),
                    LlilOp::SetReg(id0),
                ]
            }
            M::Push => {
                // RSP -= size; [RSP] = src
                let src = src_reg(iced_instr, 0);
                vec![
                    LlilOp::GetReg(24),
                    LlilOp::Sub,
                    LlilOp::SetReg(24),
                    src,
                    LlilOp::Store,
                ]
            }
            M::Pop => {
                // dst = [RSP]; RSP += size
                let dst_id = reg_id_n(iced_instr, 0);
                vec![
                    LlilOp::Load,
                    LlilOp::SetReg(dst_id),
                    LlilOp::GetReg(24),
                    LlilOp::Add,
                    LlilOp::SetReg(24),
                ]
            }
            // ── arithmetic ─────────────────────────────────────────────────
            M::Add | M::Adc => {
                let dst_id = reg_id_n(iced_instr, 0);
                let src = src_reg(iced_instr, 1);
                vec![
                    LlilOp::GetReg(dst_id),
                    src,
                    LlilOp::Add,
                    LlilOp::SetReg(dst_id),
                ]
            }
            M::Sub | M::Sbb => {
                let dst_id = reg_id_n(iced_instr, 0);
                let src = src_reg(iced_instr, 1);
                vec![
                    LlilOp::GetReg(dst_id),
                    src,
                    LlilOp::Sub,
                    LlilOp::SetReg(dst_id),
                ]
            }
            M::Inc => {
                let dst_id = reg_id_n(iced_instr, 0);
                vec![
                    LlilOp::GetReg(dst_id),
                    LlilOp::Const(1),
                    LlilOp::Add,
                    LlilOp::SetReg(dst_id),
                ]
            }
            M::Dec => {
                let dst_id = reg_id_n(iced_instr, 0);
                vec![
                    LlilOp::GetReg(dst_id),
                    LlilOp::Const(1),
                    LlilOp::Sub,
                    LlilOp::SetReg(dst_id),
                ]
            }
            M::Neg => {
                let dst_id = reg_id_n(iced_instr, 0);
                vec![
                    LlilOp::Const(0),
                    LlilOp::GetReg(dst_id),
                    LlilOp::Sub,
                    LlilOp::SetReg(dst_id),
                ]
            }
            M::Mul | M::Imul => {
                // One-operand form: RAX = RAX * src (high half in RDX not
                // representable in the flat IR — quotient-register write is
                // the honest single-destination approximation). Two/three
                // operand IMUL keeps its explicit destination.
                if iced_instr.op_count() == 1 {
                    let rax = X86LiftAdapter::reg_id(iced_x86::Register::RAX);
                    vec![
                        LlilOp::GetReg(rax),
                        src_reg(iced_instr, 0),
                        LlilOp::Mul,
                        LlilOp::SetReg(rax),
                    ]
                } else {
                    let dst_id = reg_id_n(iced_instr, 0);
                    let (a, b) = if iced_instr.op_count() >= 3 {
                        (src_reg(iced_instr, 1), src_reg(iced_instr, 2))
                    } else {
                        (LlilOp::GetReg(dst_id), src_reg(iced_instr, 1))
                    };
                    vec![a, b, LlilOp::Mul, LlilOp::SetReg(dst_id)]
                }
            }
            M::Div | M::Idiv => {
                // Always one-operand: RAX = RAX / src (remainder in RDX not
                // representable in the flat IR).
                let rax = X86LiftAdapter::reg_id(iced_x86::Register::RAX);
                vec![
                    LlilOp::GetReg(rax),
                    src_reg(iced_instr, 0),
                    LlilOp::Div,
                    LlilOp::SetReg(rax),
                ]
            }
            // ── logic ──────────────────────────────────────────────────────
            M::And => {
                let dst_id = reg_id_n(iced_instr, 0);
                let src = src_reg(iced_instr, 1);
                vec![
                    LlilOp::GetReg(dst_id),
                    src,
                    LlilOp::And,
                    LlilOp::SetReg(dst_id),
                ]
            }
            M::Or => {
                let dst_id = reg_id_n(iced_instr, 0);
                let src = src_reg(iced_instr, 1);
                vec![
                    LlilOp::GetReg(dst_id),
                    src,
                    LlilOp::Or,
                    LlilOp::SetReg(dst_id),
                ]
            }
            M::Xor => {
                let dst_id = reg_id_n(iced_instr, 0);
                // xor reg, reg → zero
                if iced_instr.op0_register() == iced_instr.op1_register() {
                    vec![LlilOp::Const(0), LlilOp::SetReg(dst_id)]
                } else {
                    let src = src_reg(iced_instr, 1);
                    vec![
                        LlilOp::GetReg(dst_id),
                        src,
                        LlilOp::Xor,
                        LlilOp::SetReg(dst_id),
                    ]
                }
            }
            M::Not => {
                let dst_id = reg_id_n(iced_instr, 0);
                vec![LlilOp::GetReg(dst_id), LlilOp::Not, LlilOp::SetReg(dst_id)]
            }
            M::Cmp | M::Test => {
                // These only set flags; no register is written in the flat IR.
                let id0 = reg_id_n(iced_instr, 0);
                let src = src_reg(iced_instr, 1);
                vec![LlilOp::GetReg(id0), src, LlilOp::Sub]
            }
            // ── shifts ─────────────────────────────────────────────────────
            M::Shl | M::Sal => {
                let dst_id = reg_id_n(iced_instr, 0);
                let count = if iced_instr.op_count() > 1 {
                    src_reg(iced_instr, 1)
                } else {
                    LlilOp::Const(1)
                };
                vec![
                    LlilOp::GetReg(dst_id),
                    count,
                    LlilOp::Lsl,
                    LlilOp::SetReg(dst_id),
                ]
            }
            M::Shr | M::Sar => {
                let dst_id = reg_id_n(iced_instr, 0);
                let count = if iced_instr.op_count() > 1 {
                    src_reg(iced_instr, 1)
                } else {
                    LlilOp::Const(1)
                };
                // SAR is sign-preserving — lifting it as Lsr corrupts every
                // negative value; use the dedicated Asr op.
                let shift = if iced_instr.mnemonic() == M::Sar {
                    LlilOp::Asr
                } else {
                    LlilOp::Lsr
                };
                vec![
                    LlilOp::GetReg(dst_id),
                    count,
                    shift,
                    LlilOp::SetReg(dst_id),
                ]
            }
            // ── control flow ───────────────────────────────────────────────
            M::Jmp => {
                let target = iced_instr.near_branch64();
                vec![LlilOp::Jump(target)]
            }
            M::Call => {
                let target = iced_instr.near_branch64();
                vec![LlilOp::Call(target)]
            }
            M::Ret | M::Retf => {
                vec![LlilOp::Return]
            }
            // ── conditional branches (Jcc) — all map to a generic Jump ─────
            M::Je
            | M::Jne
            | M::Jb
            | M::Jae
            | M::Jbe
            | M::Ja
            | M::Js
            | M::Jns
            | M::Jp
            | M::Jnp
            | M::Jl
            | M::Jge
            | M::Jle
            | M::Jg
            | M::Jo
            | M::Jno
            | M::Jcxz
            | M::Jecxz
            | M::Jrcxz => {
                vec![LlilOp::Jump(iced_instr.near_branch64())]
            }
            // ── system ─────────────────────────────────────────────────────
            M::Syscall | M::Sysenter => {
                vec![LlilOp::Syscall]
            }
            M::Nop | M::Fnop | M::Pause => {
                vec![LlilOp::Nop]
            }
            // ── fallback ───────────────────────────────────────────────────
            // The flat LlilOp stub has no Unknown/Intrinsic variant, so
            // unlisted mnemonics necessarily degrade to Nop. This adapter is
            // a coarse rustre-core bridge; the full-fidelity lifter is
            // `lift.rs` (LlilExpr trees), which dispatches every mnemonic.
            _ => vec![LlilOp::Nop],
        }
    }
}

/// Last-resort branch extraction from formatted operands string.
fn fallback_branches(instr: &Instruction) -> Vec<BranchInfo> {
    if !instr.flags.contains(InstrFlags::BRANCH) {
        return vec![];
    }
    // Try to parse "0x<hex>" or plain hex address from operands.
    let operands = instr.operands.trim();
    let hex_str = operands
        .strip_prefix("0x")
        .or_else(|| operands.strip_prefix("0X"))
        .unwrap_or(operands);
    if let Ok(addr_val) = u64::from_str_radix(hex_str, 16) {
        let bi = if instr.flags.contains(InstrFlags::CALL) {
            BranchInfo::call(addr_val)
        } else if instr.flags.contains(InstrFlags::CONDITIONAL) {
            BranchInfo::conditional_jump(addr_val, BranchCondition::Custom(0))
        } else {
            BranchInfo::unconditional_jump(addr_val)
        };
        vec![bi]
    } else {
        vec![]
    }
}

