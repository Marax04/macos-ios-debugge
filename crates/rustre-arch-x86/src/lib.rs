/// Streaming, iterator-based linear disassembler.
///
/// Decodes instructions sequentially from a byte slice, advancing by the
/// length of each successfully decoded instruction.  On decode error the
/// iterator yields `Err(CoreError)` and halts (does not advance past the
/// bad byte).
///
/// # Example
/// ```no_run
/// use rustre_arch_x86::{X86Arch, LinearDisassembler};
/// use rustre_core::address::Address;
///
/// let code: &[u8] = &[0x55, 0x48, 0x89, 0xe5, 0x90, 0xc3];
/// let arch = X86Arch::new_64bit();
/// let base = Address::new(0x1000);
/// for result in LinearDisassembler::new(&arch, code, base) {
///     let instr = result.unwrap();
///     println!("{:?}", instr);
/// }
/// ```
pub struct LinearDisassembler<'a> {
    arch: &'a X86Arch,
    bytes: &'a [u8],
    base_addr: Address,
    offset: usize,
    formatter: GasFormatter,
}

impl<'a> LinearDisassembler<'a> {
    /// Create a new linear disassembler.
    #[must_use]
    pub fn new(arch: &'a X86Arch, bytes: &'a [u8], base_addr: Address) -> Self {
        Self {
            arch,
            bytes,
            base_addr,
            offset: 0,
            formatter: X86Arch::make_formatter(),
        }
    }

    /// Return the current byte offset within the provided slice.
    #[must_use]
    pub const fn offset(&self) -> usize {
        self.offset
    }

    /// Return the current virtual address (base + offset).
    #[must_use]
    pub const fn current_address(&self) -> Address {
        Address::new(self.base_addr.0.wrapping_add(self.offset as u64))
    }

    /// Return `true` if there are no more bytes to decode.
    #[must_use]
    pub const fn is_done(&self) -> bool {
        self.offset >= self.bytes.len()
    }
}

impl Iterator for LinearDisassembler<'_> {
    type Item = Result<Instruction, CoreError>;

    fn next(&mut self) -> Option<Self::Item> {
        if self.offset >= self.bytes.len() {
            return None;
        }

        let remaining = &self.bytes[self.offset..];
        let cur_addr = Address::new(self.base_addr.0.wrapping_add(self.offset as u64));

        match self.arch.decode_one(cur_addr, remaining) {
            Ok((ref iced, len)) => {
                let instr =
                    self.arch
                        .convert_with(&mut self.formatter, cur_addr, iced, remaining);
                self.offset += len;
                Some(Ok(instr))
            }
            Err(e) => {
                // Do not advance — let the caller decide what to do.
                Some(Err(e))
            }
        }
    }
}

