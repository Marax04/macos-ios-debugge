    // ──────────────────────────────────────────────────────────────────────
    // Robustness: the decoder/disassembler/lifter must never panic on
    // adversarial input (packed/obfuscated/truncated bytes). Deterministic LCG
    // so any failure reproduces exactly.
    // ──────────────────────────────────────────────────────────────────────

    struct Lcg(u64);
    impl Lcg {
        fn next(&mut self) -> u64 {
            self.0 = self
                .0
                .wrapping_mul(6364136223846793005)
                .wrapping_add(1442695040888963407);
            self.0
        }
    }

    fn fuzz_arch(arch: &X86Arch, bits: u32, seed: u64, iters: usize) {
        let prev = std::panic::take_hook();
        std::panic::set_hook(Box::new(|_| {}));
        let mut rng = Lcg(seed);
        let mut first_panic: Option<Vec<u8>> = None;
        for _ in 0..iters {
            let len = 1 + (rng.next() % 16) as usize;
            let mut bytes = Vec::with_capacity(len);
            for _ in 0..len {
                bytes.push((rng.next() >> 24) as u8);
            }
            let bp = bytes.clone();
            let r = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
                // Every public entry point that touches raw bytes.
                let _ = crate::length::instr_length(&bytes, bits);
                let _ = crate::branch::classify_branch(&bytes);
                let _ = arch.disassemble(Address(0x1000), &bytes);
                let _ = arch.lift(Address(0x1000), &bytes);
                // Streaming disassembly over the whole buffer (bounded).
                let dis = LinearDisassembler::new(arch, &bytes, Address(0x2000));
                for instr in dis.take(48).flatten() {
                    let _ = arch.get_branches(&instr);
                }
            }));
            if r.is_err() {
                first_panic = Some(bp);
                break;
            }
        }
        std::panic::set_hook(prev);
        assert!(
            first_panic.is_none(),
            "panicked on bytes={:02x?}",
            first_panic
        );
    }

    #[test]
    fn fuzz_decode_disasm_lift_never_panics_64() {
        fuzz_arch(&x64(), 64, 0xdead_beef_0bad_f00d, 40_000);
    }

    #[test]
    fn fuzz_decode_disasm_lift_never_panics_32() {
        fuzz_arch(&x32(), 32, 0x1234_4321_abcd_dcba, 40_000);
    }

    #[test]
    fn fuzz_decode_disasm_lift_never_panics_16() {
        fuzz_arch(&X86Arch::new_16bit(), 16, 0xcafe_d00d_5566_7788, 25_000);
    }

    /// Linear-sweep self-consistency: over a buffer of back-to-back valid
    /// instructions, each decoded length must match the standalone length
    /// scanner, and offsets must advance monotonically without overrun.
    #[test]
    fn linear_sweep_matches_length_scanner() {
        // push rbp; mov rbp,rsp; sub rsp,0x20; xor eax,eax; add rax,1;
        // movzx ecx,al; ret
        let code: &[u8] = &[
            0x55, 0x48, 0x89, 0xE5, 0x48, 0x83, 0xEC, 0x20, 0x31, 0xC0, 0x48, 0x83, 0xC0, 0x01,
            0x0F, 0xB6, 0xC8, 0xC3,
        ];
        let arch = x64();
        let mut off = 0usize;
        let dis = LinearDisassembler::new(&arch, code, Address(0x1000));
        for item in dis {
            let instr = item.expect("valid instruction");
            assert_eq!(
                instr.size,
                crate::length::instr_length(&code[off..], 64).unwrap(),
                "length scanner disagrees with decoder at offset {off}"
            );
            off += instr.size;
            assert!(off <= code.len(), "sweep overran the buffer");
        }
        assert_eq!(off, code.len(), "sweep did not cover the whole buffer");
    }
