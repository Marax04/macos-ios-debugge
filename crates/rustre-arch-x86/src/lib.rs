/// The primary architecture descriptor.
///
/// Construct with [`X86Arch::new_16bit`], [`X86Arch::new_32bit`], or
/// [`X86Arch::new_64bit`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct X86Arch {
    bits: u32,
}

impl Default for X86Arch {
    fn default() -> Self {
        Self::new_64bit()
    }
}

impl X86Arch {
    /// Create a 16-bit (real-mode / 8086) architecture descriptor.
    #[must_use]
    pub const fn new_16bit() -> Self {
        Self { bits: 16 }
    }

    /// Create a 32-bit (IA-32 / i386) architecture descriptor.
    #[must_use]
    pub const fn new_32bit() -> Self {
        Self { bits: 32 }
    }

    /// Create a 64-bit (AMD64 / x86-64) architecture descriptor.
    #[must_use]
    pub const fn new_64bit() -> Self {
        Self { bits: 64 }
    }

    /// The bitness value (16, 32, or 64).
    #[must_use]
    pub const fn bits(&self) -> u32 {
        self.bits
    }

    /// Decode one instruction at `address` and lift it to a sequence of LLIL
    /// instructions.
    ///
    /// Returns the lifted [`lift::X86Lifter`] output together with the decoded
    /// instruction's byte length. This is the high-level entry point that ties
    /// decoding and lifting together.
    pub fn lift(
        &self,
        address: Address,
        bytes: &[u8],
    ) -> Result<(Vec<rustre_il_llil::LlilAnnotatedInstr>, usize), CoreError> {
        let (iced, len) = self.decode_one(address, bytes)?;
        let mut lifter = lift::X86Lifter::new(self.bits);
        let lifted = lifter.lift(&iced, address, len);
        Ok((lifted, len))
    }

    // ------------------------------------------------------------------
    // Internal helpers
    // ------------------------------------------------------------------

    /// Decode **one** instruction at `address` from `bytes` using iced-x86.
    fn decode_one(
        &self,
        address: Address,
        bytes: &[u8],
    ) -> Result<(IcedInstruction, usize), CoreError> {
        if bytes.is_empty() {
            return Err(CoreError::PluginError {
                plugin: "x86".into(),
                message: "No bytes to disassemble".into(),
            });
        }

        let mut decoder = Decoder::with_ip(self.bits, bytes, address.0, DecoderOptions::NONE);

        let iced = decoder.decode();

        if iced.is_invalid() {
            return Err(CoreError::PluginError {
                plugin: "x86".into(),
                message: format!("Invalid instruction at 0x{:x}", address.0),
            });
        }

        let len = iced.len();
        Ok((iced, len))
    }

    /// Build the GAS (AT&T) formatter used by [`Self::convert`]. Callers that
    /// convert many instructions should build it once and reuse it via
    /// [`Self::convert_with`].
    fn make_formatter() -> GasFormatter {
        let mut formatter = GasFormatter::new();
        formatter
            .options_mut()
            .set_space_after_operand_separator(true);
        formatter.options_mut().set_rip_relative_addresses(true);
        formatter
    }

    /// Convert an [`IcedInstruction`] to our [`Instruction`] type.
    fn convert(&self, address: Address, iced: &IcedInstruction, raw_bytes: &[u8]) -> Instruction {
        let mut formatter = Self::make_formatter();
        self.convert_with(&mut formatter, address, iced, raw_bytes)
    }

    /// Like [`Self::convert`], but reuses a caller-owned formatter (one string
    /// buffer allocation instead of a formatter + buffer per instruction).
    fn convert_with(
        &self,
        formatter: &mut GasFormatter,
        address: Address,
        iced: &IcedInstruction,
        raw_bytes: &[u8],
    ) -> Instruction {
        let len = iced.len();

        let mut output = StringOutput::new();
        formatter.format(iced, &mut output);
        let full_text = output.0;

        // Split on first whitespace: everything before is the mnemonic,
        // everything after is operands.
        let (mnemonic, operands) = split_mnemonic_operands(&full_text);

        let flags = flow_control_to_flags(iced);

        {
            let mut instr = Instruction::new(address, len, mnemonic, raw_bytes[..len].to_vec());
            instr.operands = operands;
            instr.flags = flags;
            instr
        }
    }
}

/// Split a full formatted instruction string into `(mnemonic, operands)`.
/// e.g. `"movq %rax, %rbx"` → `("movq", "%rax, %rbx")`.
fn split_mnemonic_operands(text: &str) -> (String, String) {
    let text = text.trim();
    if let Some(pos) = text.find(|c: char| c.is_whitespace()) {
        let mnemonic = text[..pos].trim().to_string();
        let operands = text[pos..].trim().to_string();
        (mnemonic, operands)
    } else {
        (text.to_string(), String::new())
    }
}

/// Map iced-x86 [`FlowControl`] (plus memory-access information) to our
/// [`InstrFlags`] bit set.
fn flow_control_to_flags(iced: &IcedInstruction) -> InstrFlags {
    let mut flags = InstrFlags::NONE;

    match iced.flow_control() {
        FlowControl::Next => {}
        FlowControl::UnconditionalBranch => {
            flags |= InstrFlags::BRANCH;
        }
        FlowControl::ConditionalBranch => {
            flags |= InstrFlags::BRANCH | InstrFlags::CONDITIONAL;
        }
        FlowControl::Call => {
            flags |= InstrFlags::BRANCH | InstrFlags::CALL;
        }
        FlowControl::Return => {
            flags |= InstrFlags::RET;
        }
        FlowControl::IndirectBranch => {
            flags |= InstrFlags::BRANCH | InstrFlags::INDIRECT;
        }
        FlowControl::IndirectCall => {
            flags |= InstrFlags::BRANCH | InstrFlags::CALL | InstrFlags::INDIRECT;
        }
        FlowControl::XbeginXabortXend => {
            flags |= InstrFlags::BRANCH | InstrFlags::CONDITIONAL;
        }
        FlowControl::Exception => {
            flags |= InstrFlags::BARRIER;
        }
        FlowControl::Interrupt => {
            flags |= InstrFlags::BARRIER;
        }
    }

    // Determine memory-access flags via InstructionInfoFactory.
    let mut factory = InstructionInfoFactory::new();
    let info = factory.info(iced);

    let has_mem_read = info.used_memory().iter().any(|m| {
        matches!(
            m.access(),
            OpAccess::Read | OpAccess::CondRead | OpAccess::ReadWrite | OpAccess::ReadCondWrite
        )
    });
    let has_mem_write = info.used_memory().iter().any(|m| {
        matches!(
            m.access(),
            OpAccess::Write | OpAccess::CondWrite | OpAccess::ReadWrite | OpAccess::ReadCondWrite
        )
    });

    // Fall back to opkind heuristic when InstructionInfoFactory finds nothing
    // (e.g. push/pop on some microarchitectures).
    let memory_operand_present = (0..iced.op_count()).any(|i| {
        iced.op_kind(i) == OpKind::Memory
            || iced.op_kind(i) == OpKind::MemorySegSI
            || iced.op_kind(i) == OpKind::MemorySegESI
            || iced.op_kind(i) == OpKind::MemorySegRSI
            || iced.op_kind(i) == OpKind::MemorySegDI
            || iced.op_kind(i) == OpKind::MemorySegEDI
            || iced.op_kind(i) == OpKind::MemorySegRDI
            || iced.op_kind(i) == OpKind::MemoryESDI
            || iced.op_kind(i) == OpKind::MemoryESEDI
            || iced.op_kind(i) == OpKind::MemoryESRDI
    });

    if has_mem_read {
        flags |= InstrFlags::READ_MEM;
    }
    if has_mem_write {
        flags |= InstrFlags::WRITE_MEM;
    }
    // Fallback: InstructionInfoFactory found no memory accesses but a memory
    // operand is present. We cannot reliably determine directionality without
    // inspecting the mnemonic, so we conservatively set only READ_MEM to avoid
    // falsely marking write-only instructions (e.g. MOV [mem], reg) as readers.
    if !has_mem_read && !has_mem_write && memory_operand_present && iced.memory_size() != MemorySize::Unknown {
        flags |= InstrFlags::READ_MEM;
    }

    flags
}

/// Extract branch targets from a decoded iced instruction.
/// Returns a list of [`BranchInfo`] entries (may be empty for non-branches).
fn extract_branches(iced: &IcedInstruction) -> Vec<BranchInfo> {
    let mut out = Vec::new();

    match iced.flow_control() {
        FlowControl::UnconditionalBranch => {
            let target = iced.near_branch_target();
            if target != 0 {
                out.push(BranchInfo::unconditional_jump(target));
            }
        }
        FlowControl::ConditionalBranch => {
            let target = iced.near_branch_target();
            if target != 0 {
                out.push(BranchInfo::conditional_jump(
                    target,
                    BranchCondition::Custom(0),
                ));
            }
        }
        FlowControl::Call => {
            let target = iced.near_branch_target();
            if target != 0 {
                out.push(BranchInfo::call(target));
            }
        }
        FlowControl::XbeginXabortXend => {
            let target = iced.near_branch_target();
            if target != 0 {
                out.push(BranchInfo::conditional_jump(
                    target,
                    BranchCondition::Custom(0),
                ));
            }
        }
        // Indirect / Return / Exception / Next → no static target
        _ => {}
    }

    out
}

