/// A thin wrapper around [`String`] that implements [`iced_x86::FormatterOutput`]
/// so we can capture formatted disassembly text.
struct StringOutput(String);

impl StringOutput {
    fn new() -> Self {
        Self(String::with_capacity(64))
    }
}

impl iced_x86::FormatterOutput for StringOutput {
    fn write(&mut self, text: &str, _kind: iced_x86::FormatterTextKind) {
        self.0.push_str(text);
    }
}

