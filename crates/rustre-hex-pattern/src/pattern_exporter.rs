//! `pattern_exporter` — Export/import patterns to external formats.
//!
//! Supports:
//! - Export to 010 Editor template (.bt)
//! - Export to Kaitai Struct (.ksy, YAML)
//! - Export to Wireshark Lua dissector
//! - Import from Kaitai Struct
//! - Import from Synalysis pattern

use std::fmt::Write as FmtWrite;

use serde::{Deserialize, Serialize};

// ─────────────────────────────────────────────────────────────────────────────
// ExportError
// ─────────────────────────────────────────────────────────────────────────────

#[derive(Debug, thiserror::Error)]
pub enum ExportError {
    #[error("unsupported type for {format}: {type_name}")]
    UnsupportedType { format: String, type_name: String },
    #[error("parse error: {0}")]
    Parse(String),
    #[error("I/O error: {0}")]
    Io(String),
    #[error("field '{field}': {reason}")]
    Field { field: String, reason: String },
}

// ─────────────────────────────────────────────────────────────────────────────
// Intermediate representation
// ─────────────────────────────────────────────────────────────────────────────

/// Endianness of a field.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
pub enum Endian {
    #[default]
    Little,
    Big,
}

impl Endian {
    const fn as_ksy(&self) -> &str {
        match self {
            Endian::Little => "le",
            Endian::Big => "be",
        }
    }
}

/// Primitive field types in the IR.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum IrType {
    U8,
    U16(Endian),
    U32(Endian),
    U64(Endian),
    I8,
    I16(Endian),
    I32(Endian),
    I64(Endian),
    F32(Endian),
    F64(Endian),
    Bytes(usize),
    CString,
    String { encoding: String },
    Struct(String),
    Array { elem_type: Box<IrType>, count: IrArrayCount },
    Union { tag_field: String, variants: Vec<IrUnionVariant> },
    Padding(usize),
}

/// How many elements are in an array.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum IrArrayCount {
    Fixed(usize),
    FieldRef(String),
    NullTerminated,
}

/// A variant in a union type.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct IrUnionVariant {
    pub tag_value: String,
    pub type_name: String,
}

/// A single field in an IR struct.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct IrField {
    pub name: String,
    pub ty: IrType,
    pub comment: String,
    pub condition: Option<String>,
}

/// An IR struct definition.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct IrStruct {
    pub name: String,
    pub fields: Vec<IrField>,
    pub comment: String,
    pub version: Option<u32>,
}

/// A full pattern/template in IR form.
#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct IrPattern {
    pub name: String,
    pub description: String,
    pub file_extensions: Vec<String>,
    pub structs: Vec<IrStruct>,
    pub root_struct: String,
    pub endian: Endian,
}

// ─────────────────────────────────────────────────────────────────────────────
// Export to 010 Editor .bt
// ─────────────────────────────────────────────────────────────────────────────

/// Export an `IrPattern` to a 010 Editor template string.
pub fn export_010_editor(pattern: &IrPattern) -> Result<String, ExportError> {
    let mut out = String::new();

    writeln!(out, "//------------------------------------------------").unwrap();
    writeln!(out, "// 010 Editor Binary Template").unwrap();
    writeln!(out, "// Name: {}", pattern.name).unwrap();
    writeln!(out, "// Description: {}", pattern.description).unwrap();
    writeln!(out, "// Generated by rustre-hex-pattern").unwrap();
    writeln!(out, "//------------------------------------------------").unwrap();
    writeln!(out).unwrap();

    // Set endianness
    match pattern.endian {
        Endian::Little => writeln!(out, "LittleEndian();").unwrap(),
        Endian::Big => writeln!(out, "BigEndian();").unwrap(),
    }
    writeln!(out).unwrap();

    for st in &pattern.structs {
        if !st.comment.is_empty() {
            writeln!(out, "// {}", st.comment).unwrap();
        }
        writeln!(out, "typedef struct {{").unwrap();
        for field in &st.fields {
            let type_str = ir_type_to_010(&field.ty)?;
            if let Some(cond) = &field.condition {
                writeln!(out, "    if ({cond}) {{").unwrap();
                if !field.comment.is_empty() {
                    writeln!(out, "        // {}", field.comment).unwrap();
                }
                writeln!(out, "        {type_str} {};", field.name).unwrap();
                writeln!(out, "    }}").unwrap();
            } else {
                if !field.comment.is_empty() {
                    writeln!(out, "    // {}", field.comment).unwrap();
                }
                writeln!(out, "    {type_str} {};", field.name).unwrap();
            }
        }
        writeln!(out, "}} {};", st.name).unwrap();
        writeln!(out).unwrap();
    }

    // Root instantiation
    writeln!(out, "{} {};", pattern.root_struct, pattern.root_struct.to_lowercase()).unwrap();

    Ok(out)
}

fn ir_type_to_010(ty: &IrType) -> Result<String, ExportError> {
    Ok(match ty {
        IrType::U8 => "uchar".to_string(),
        IrType::U16(_) => "uint16".to_string(),
        IrType::U32(_) => "uint32".to_string(),
        IrType::U64(_) => "uint64".to_string(),
        IrType::I8 => "char".to_string(),
        IrType::I16(_) => "int16".to_string(),
        IrType::I32(_) => "int32".to_string(),
        IrType::I64(_) => "int64".to_string(),
        IrType::F32(_) => "float".to_string(),
        IrType::F64(_) => "double".to_string(),
        IrType::Bytes(n) => format!("uchar[{n}]"),
        IrType::CString => "string".to_string(),
        IrType::String { .. } => "string".to_string(),
        IrType::Struct(name) => name.clone(),
        IrType::Array { elem_type, count } => {
            let elem = ir_type_to_010(elem_type)?;
            match count {
                IrArrayCount::Fixed(n) => format!("{elem}[{n}]"),
                IrArrayCount::FieldRef(f) => format!("{elem}[{f}]"),
                IrArrayCount::NullTerminated => format!("{elem}[]"),
            }
        }
        IrType::Union { .. } => "// union (unsupported in 010 directly)".to_string(),
        IrType::Padding(n) => format!("uchar padding[{n}]"),
    })
}

