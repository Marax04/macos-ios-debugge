/// Export to Kaitai Struct YAML format.
pub fn export_kaitai(pattern: &IrPattern) -> Result<String, ExportError> {
    let mut out = String::new();

    writeln!(out, "meta:").unwrap();
    writeln!(out, "  id: {}", to_snake_case(&pattern.name)).unwrap();
    writeln!(out, "  title: \"{}\"", pattern.name).unwrap();
    if !pattern.file_extensions.is_empty() {
        writeln!(out, "  file-extension:").unwrap();
        for ext in &pattern.file_extensions {
            writeln!(out, "    - {ext}").unwrap();
        }
    }
    writeln!(out, "  endian: {}", pattern.endian.as_ksy()).unwrap();
    writeln!(out).unwrap();

    writeln!(out, "seq:").unwrap();
    // Root struct fields
    if let Some(root) = pattern.structs.iter().find(|s| s.name == pattern.root_struct) {
        for field in &root.fields {
            write_ksy_field(&mut out, field, 2)?;
        }
    }

    if pattern.structs.len() > 1 {
        writeln!(out).unwrap();
        writeln!(out, "types:").unwrap();
        for st in &pattern.structs {
            if st.name == pattern.root_struct {
                continue;
            }
            writeln!(out, "  {}:", to_snake_case(&st.name)).unwrap();
            writeln!(out, "    seq:").unwrap();
            for field in &st.fields {
                write_ksy_field(&mut out, field, 6)?;
            }
        }
    }

    Ok(out)
}

fn write_ksy_field(out: &mut String, field: &IrField, indent: usize) -> Result<(), ExportError> {
    let pad = " ".repeat(indent);
    let name = to_snake_case(&field.name);
    writeln!(out, "{pad}- id: {name}").unwrap();
    let type_str = ir_type_to_ksy(&field.ty)?;
    writeln!(out, "{pad}  type: {type_str}").unwrap();
    if !field.comment.is_empty() {
        writeln!(out, "{pad}  doc: \"{}\"", field.comment).unwrap();
    }
    if let Some(cond) = &field.condition {
        writeln!(out, "{pad}  if: {cond}").unwrap();
    }
    Ok(())
}

fn ir_type_to_ksy(ty: &IrType) -> Result<String, ExportError> {
    Ok(match ty {
        IrType::U8 => "u1".to_string(),
        IrType::U16(e) => if *e == Endian::Little { "u2le".to_string() } else { "u2be".to_string() },
        IrType::U32(e) => if *e == Endian::Little { "u4le".to_string() } else { "u4be".to_string() },
        IrType::U64(e) => if *e == Endian::Little { "u8le".to_string() } else { "u8be".to_string() },
        IrType::I8 => "s1".to_string(),
        IrType::I16(e) => if *e == Endian::Little { "s2le".to_string() } else { "s2be".to_string() },
        IrType::I32(e) => if *e == Endian::Little { "s4le".to_string() } else { "s4be".to_string() },
        IrType::I64(e) => if *e == Endian::Little { "s8le".to_string() } else { "s8be".to_string() },
        IrType::F32(e) => if *e == Endian::Little { "f4le".to_string() } else { "f4be".to_string() },
        IrType::F64(e) => if *e == Endian::Little { "f8le".to_string() } else { "f8be".to_string() },
        IrType::Bytes(n) => format!("bytes[{n}]"),
        IrType::CString => "strz".to_string(),
        IrType::String { encoding } => format!("str (encoding: {encoding})"),
        IrType::Struct(name) => to_snake_case(name),
        IrType::Array { elem_type, count } => {
            let et = ir_type_to_ksy(elem_type)?;
            match count {
                IrArrayCount::Fixed(n) => format!("{et}[{n}]"),
                IrArrayCount::FieldRef(f) => format!("{et}[{f}]"),
                IrArrayCount::NullTerminated => et,
            }
        }
        IrType::Union { .. } => "bytes".to_string(),
        IrType::Padding(n) => format!("bytes[{n}]"),
    })
}

