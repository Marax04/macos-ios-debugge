// Import from Synalysis pattern (simplified)
// ─────────────────────────────────────────────────────────────────────────────

/// Import from Synalysis grammar format (simplified XML-like parser).
pub fn import_synalysis(xml: &str) -> Result<IrPattern, ExportError> {
    let mut pattern = IrPattern {
        endian: Endian::Little,
        name: "SynalysisPattern".to_string(),
        ..Default::default()
    };
    let mut fields: Vec<IrField> = vec![];

    // Very simplified parser — extracts <field name="..." type="..." />
    for line in xml.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with("<grammar") {
            if let Some(id_start) = trimmed.find("id=\"") {
                let rest = &trimmed[id_start + 4..];
                if let Some(id_end) = rest.find('"') {
                    pattern.name = rest[..id_end].to_string();
                }
            }
        }
        if trimmed.starts_with("<field") || trimmed.starts_with("<structure") {
            let name = extract_xml_attr(trimmed, "name").unwrap_or("field".to_string());
            let type_str = extract_xml_attr(trimmed, "type").unwrap_or("u1".to_string());
            let ty = synalysis_type_to_ir(&type_str, pattern.endian);
            let comment = extract_xml_attr(trimmed, "comment").unwrap_or_default();
            fields.push(IrField {
                name,
                ty,
                comment,
                condition: None,
            });
        }
    }

    let root_name = to_pascal_case(&pattern.name);
    pattern.root_struct = root_name.clone();
    pattern.structs.push(IrStruct {
        name: root_name,
        fields,
        comment: String::new(),
        version: None,
    });

    Ok(pattern)
}

fn synalysis_type_to_ir(s: &str, endian: Endian) -> IrType {
    match s {
        "uint8" | "byte" => IrType::U8,
        "uint16" => IrType::U16(endian),
        "uint32" => IrType::U32(endian),
        "uint64" => IrType::U64(endian),
        "int8" => IrType::I8,
        "int16" => IrType::I16(endian),
        "int32" => IrType::I32(endian),
        "int64" => IrType::I64(endian),
        "float" => IrType::F32(endian),
        "double" => IrType::F64(endian),
        "string" => IrType::CString,
        _ => IrType::Struct(to_pascal_case(s)),
    }
}

// ─────────────────────────────────────────────────────────────────────────────
// String helpers
// ─────────────────────────────────────────────────────────────────────────────

fn to_snake_case(s: &str) -> String {
    let mut out = String::new();
    for (i, c) in s.chars().enumerate() {
        if c.is_uppercase() && i > 0 {
            out.push('_');
        }
        out.push(c.to_lowercase().next().unwrap());
    }
    out
}

fn to_pascal_case(s: &str) -> String {
    s.split('_')
        .map(|w| {
            let mut c = w.chars();
            match c.next() {
                None => String::new(),
                Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
            }
        })
        .collect()
}

fn strip_key<'a>(line: &'a str, key: &str) -> Option<&'a str> {
    if line.starts_with(key) {
        Some(line[key.len()..].trim())
    } else {
        None
    }
}

fn extract_xml_attr(xml: &str, attr: &str) -> Option<String> {
    let search = format!("{attr}=\"");
    let start = xml.find(&search)? + search.len();
    let rest = &xml[start..];
    let end = rest.find('"')?;
    Some(rest[..end].to_string())
}

