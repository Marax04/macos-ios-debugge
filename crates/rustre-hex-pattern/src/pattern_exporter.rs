/// Export to a Wireshark Lua dissector.
pub fn export_wireshark_lua(pattern: &IrPattern) -> Result<String, ExportError> {
    let mut out = String::new();
    let proto_name = to_snake_case(&pattern.name);
    let proto_desc = &pattern.description;

    writeln!(out, "-- Wireshark Lua dissector: {}", pattern.name).unwrap();
    writeln!(out, "-- Generated by rustre-hex-pattern").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "local {proto_name}_proto = Proto(\"{proto_name}\", \"{proto_desc}\")").unwrap();
    writeln!(out).unwrap();

    // ProtoField declarations
    writeln!(out, "local f = {{}}").unwrap();
    if let Some(root) = pattern.structs.iter().find(|s| s.name == pattern.root_struct) {
        for field in &root.fields {
            let lua_type = ir_type_to_lua_ftype(&field.ty);
            let field_id = format!("{proto_name}.{}", to_snake_case(&field.name));
            writeln!(
                out,
                "f.{} = ProtoField.{}(\"{field_id}\", \"{}\", base.HEX)",
                to_snake_case(&field.name),
                lua_type,
                field.name
            )
            .unwrap();
        }
    }
    writeln!(out).unwrap();
    writeln!(out, "{proto_name}_proto.fields = f").unwrap();
    writeln!(out).unwrap();

    // Dissector function
    writeln!(out, "function {proto_name}_proto.dissector(buffer, pinfo, tree)").unwrap();
    writeln!(out, "    pinfo.cols.protocol = \"{proto_name}\"").unwrap();
    writeln!(out, "    local subtree = tree:add({proto_name}_proto, buffer())").unwrap();
    writeln!(out, "    local offset = 0").unwrap();

    if let Some(root) = pattern.structs.iter().find(|s| s.name == pattern.root_struct) {
        for field in &root.fields {
            let size = ir_type_lua_size(&field.ty);
            let fn_name = to_snake_case(&field.name);
            writeln!(
                out,
                "    subtree:add(f.{fn_name}, buffer(offset, {size}))"
            )
            .unwrap();
            writeln!(out, "    offset = offset + {size}").unwrap();
        }
    }

    writeln!(out, "end").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "-- Register as heuristic dissector or to a port:").unwrap();
    writeln!(out, "-- DissectorTable.get(\"tcp.port\"):add(12345, {proto_name}_proto)").unwrap();

    Ok(out)
}

const fn ir_type_to_lua_ftype(ty: &IrType) -> &'static str {
    match ty {
        IrType::U8 | IrType::I8 => "uint8",
        IrType::U16(_) | IrType::I16(_) => "uint16",
        IrType::U32(_) | IrType::I32(_) => "uint32",
        IrType::U64(_) | IrType::I64(_) => "uint64",
        IrType::F32(_) => "float",
        IrType::F64(_) => "double",
        _ => "bytes",
    }
}

const fn ir_type_lua_size(ty: &IrType) -> usize {
    match ty {
        IrType::U8 | IrType::I8 => 1,
        IrType::U16(_) | IrType::I16(_) => 2,
        IrType::U32(_) | IrType::I32(_) | IrType::F32(_) => 4,
        IrType::U64(_) | IrType::I64(_) | IrType::F64(_) => 8,
        IrType::Bytes(n) | IrType::Padding(n) => *n,
        _ => 0,
    }
}

// ─────────────────────────────────────────────────────────────────────────────
// Import from Kaitai Struct (simplified YAML parser)
// ─────────────────────────────────────────────────────────────────────────────

/// Import an `IrPattern` from a simplified Kaitai Struct YAML.
/// This handles common cases; full YAML parsing would require a dependency.
pub fn import_kaitai(yaml: &str) -> Result<IrPattern, ExportError> {
    let mut pattern = IrPattern {
        endian: Endian::Little,
        ..Default::default()
    };
    let mut root_fields: Vec<IrField> = vec![];
    let mut in_seq = false;
    let mut in_meta = false;
    let mut current_field: Option<(String, IrType)> = None;

    for line in yaml.lines() {
        let trimmed = line.trim();

        // Section detection
        if trimmed == "meta:" {
            in_meta = true;
            in_seq = false;
            continue;
        }
        if trimmed == "seq:" {
            in_seq = true;
            in_meta = false;
            continue;
        }
        if trimmed == "types:" {
            in_seq = false;
            in_meta = false;
            continue;
        }

        if in_meta {
            if let Some(val) = strip_key(trimmed, "id:") {
                pattern.name = val.to_string();
            }
            if let Some(val) = strip_key(trimmed, "title:") {
                pattern.description = val.trim_matches('"').to_string();
            }
            if let Some(val) = strip_key(trimmed, "endian:") {
                pattern.endian = if val == "le" { Endian::Little } else { Endian::Big };
            }
        }

        if in_seq {
            if trimmed.starts_with("- id:") {
                // Flush previous field
                if let Some((name, ty)) = current_field.take() {
                    root_fields.push(IrField {
                        name,
                        ty,
                        comment: String::new(),
                        condition: None,
                    });
                }
                let name = trimmed["- id:".len()..].trim().to_string();
                current_field = Some((name, IrType::Bytes(1)));
            } else if let Some(ref mut f) = current_field {
                if let Some(val) = strip_key(trimmed, "type:") {
                    f.1 = ksy_type_to_ir(val, pattern.endian);
                }
            }
        }
    }

    if let Some((name, ty)) = current_field {
        root_fields.push(IrField {
            name,
            ty,
            comment: String::new(),
            condition: None,
        });
    }

    let root_name = if pattern.name.is_empty() {
        "Root".to_string()
    } else {
        to_pascal_case(&pattern.name)
    };

    pattern.root_struct = root_name.clone();
    pattern.structs.push(IrStruct {
        name: root_name,
        fields: root_fields,
        comment: String::new(),
        version: None,
    });

    Ok(pattern)
}

fn ksy_type_to_ir(s: &str, endian: Endian) -> IrType {
    match s {
        "u1" => IrType::U8,
        "u2le" => IrType::U16(Endian::Little),
        "u2be" => IrType::U16(Endian::Big),
        "u2" => IrType::U16(endian),
        "u4le" => IrType::U32(Endian::Little),
        "u4be" => IrType::U32(Endian::Big),
        "u4" => IrType::U32(endian),
        "u8le" => IrType::U64(Endian::Little),
        "u8be" => IrType::U64(Endian::Big),
        "u8" => IrType::U64(endian),
        "s1" => IrType::I8,
        "s2le" => IrType::I16(Endian::Little),
        "s2be" => IrType::I16(Endian::Big),
        "s2" => IrType::I16(endian),
        "s4le" => IrType::I32(Endian::Little),
        "s4be" => IrType::I32(Endian::Big),
        "s4" => IrType::I32(endian),
        "s8le" => IrType::I64(Endian::Little),
        "s8be" => IrType::I64(Endian::Big),
        "s8" => IrType::I64(endian),
        "f4le" => IrType::F32(Endian::Little),
        "f4be" => IrType::F32(Endian::Big),
        "f4" => IrType::F32(endian),
        "f8le" => IrType::F64(Endian::Little),
        "f8be" => IrType::F64(Endian::Big),
        "f8" => IrType::F64(endian),
        "strz" => IrType::CString,
        _ => IrType::Struct(to_pascal_case(s)),
    }
}

